/**
 * Curated "verse of the day" references: well-known, encouraging verses.
 *
 * ONLY references live here; the verse text is always extracted from the
 * downloaded public-domain source files by `npm run verses:build`
 * (scripts/build-daily-verses.ts). Never type verse text by hand.
 *
 * Rules (checked by references.test.ts and the generator):
 * - exactly 366 entries (one per day of a leap year), no duplicates and no
 *   overlapping verses;
 * - a single verse or a same-chapter range of at most 3 verses
 *   (1 Corinthians 13:4-7 is the one allowed 4-verse exception);
 * - "Psalm" (singular) for one psalm.
 *
 * The list is grouped by book for easy review; `orderForDays()` in
 * ./order.ts spreads it over the year so a book never repeats on two
 * consecutive days.
 *
 * `stripPrefix`: psalm superscriptions are part of verse 1 in both sources
 * (e.g. "A Psalm by David. Yahweh is my shepherd..."). The exact title text
 * per translation is removed; the generator fails if the source text does not
 * start with it.
 */

